def validate_and_generate_dataset():
    """Validate 100 questions, write JSONL and cryptographic manifest."""
    assert len(QUESTIONS) == 100, f"Expected exactly 100 questions, got {len(QUESTIONS)}"

    # Validate unique IDs
    ids = [q["id"] for q in QUESTIONS]
    assert len(ids) == len(set(ids)), (
        f"Duplicate question IDs detected: {len(ids)} vs {len(set(ids))}"
    )

    # Validate unique question text
    q_texts = [q["question"].strip().lower() for q in QUESTIONS]
    assert len(q_texts) == len(set(q_texts)), "Duplicate question texts detected"

    # Validate category counts (exactly 20 per category)
    cats = {}
    for q in QUESTIONS:
        cats[q["category"]] = cats.get(q["category"], 0) + 1

    expected_categories = {
        "single_hop": 20,
        "two_hop": 20,
        "three_hop": 20,
        "aggregation": 20,
        "out_of_scope": 20,
    }
    assert cats == expected_categories, (
        f"Category distribution mismatch: {cats} vs {expected_categories}"
    )

    # Validate required fields
    for q in QUESTIONS:
        assert "id" in q and q["id"].startswith("Q"), f"Invalid ID in {q}"
        assert "question" in q and len(q["question"]) > 10, f"Invalid question text in {q}"
        assert "category" in q and q["category"] in expected_categories, f"Invalid category in {q}"
        assert "answerable" in q, f"Missing answerable boolean in {q}"
        assert "gold_answer" in q and len(q["gold_answer"]) > 5, f"Missing gold answer in {q}"
        assert "answer_criteria" in q and len(q["answer_criteria"]) > 5, (
            f"Missing answer criteria in {q}"
        )
        assert "expected_facts" in q and isinstance(q["expected_facts"], list), (
            f"Invalid expected_facts in {q}"
        )
        if q["answerable"]:
            assert len(q["source_documents"]) > 0, (
                f"Answerable question {q['id']} must have source documents"
            )
            assert q["category"] != "out_of_scope", (
                f"Answerable question {q['id']} cannot be out_of_scope"
            )
        else:
            assert q["category"] == "out_of_scope", (
                f"Unanswerable question {q['id']} must be out_of_scope"
            )
            assert "refusal" in q["gold_answer"].lower(), (
                f"Unanswerable question {q['id']} must record refusal expectation"
            )

    # Ensure uniform schema with difficulty and integer hop_count
    difficulty_map = {
        "single_hop": "easy",
        "two_hop": "medium",
        "three_hop": "hard",
        "aggregation": "hard",
        "out_of_scope": "medium",
    }
    for q in QUESTIONS:
        if "difficulty" not in q:
            q["difficulty"] = difficulty_map[q["category"]]
        if q["hop_count"] is None:
            q["hop_count"] = 0
        if "question_id" not in q:
            q["question_id"] = q["id"]

    # Save to primary repo path and eval/datasets path
    out_paths = [
        Path("benchmarks/questions/graphmind_eval_100q_v1.jsonl"),
        Path("eval/datasets/graphmind_eval_v1.jsonl"),
    ]

    for p in out_paths:
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as f:
            for q in QUESTIONS:
                f.write(json.dumps(q, ensure_ascii=False) + "\n")
        print(f"Saved 100 questions to {p}")

    # Compute SHA-256 checksum of the dataset file with newline normalization
    sha256_hash = hashlib.sha256()
    with open(out_paths[0], "rb") as f:
        data = f.read().replace(b"\r\n", b"\n")
        sha256_hash.update(data)
    checksum = sha256_hash.hexdigest()

    manifest_templates = [
        (
            Path("benchmarks/questions/dataset_manifest_100q.json"),
            "graphmind_eval_100q_v1.jsonl",
        ),
        (
            Path("eval/datasets/dataset_manifest.json"),
            "graphmind_eval_v1.jsonl",
        ),
    ]

    for mp, fname in manifest_templates:
        manifest = {
            "dataset_name": "GraphMind SEC 10-K Evaluation Benchmark (100 Questions)",
            "version": DATASET_VERSION,
            "release_date": "2026-10-17",
            "record_count": len(QUESTIONS),
            "total_questions": len(QUESTIONS),
            "dataset_filename": fname,
            "sha256_checksum": checksum,
            "category_distribution": cats,
            "categories": cats,
            "filers_covered": [
                "NVDA",
                "AMD",
                "INTC",
                "AAPL",
                "AVGO",
                "MSFT",
                "GOOGL",
                "AMZN",
                "MU",
                "QCOM",
            ],
            "ground_truth_policy": "All answerable questions verified directly against Item 1, 1A, 7, and Exhibit 21 of SEC 10-K filings. All unanswerable questions explicitly document unindexed or non-public status.",
            "schema_fields": [
                "id",
                "question_id",
                "question",
                "category",
                "difficulty",
                "hop_count",
                "answerable",
                "gold_answer",
                "expected_facts",
                "required_entities",
                "source_documents",
                "source_section",
                "source_passage_ids",
                "answer_criteria",
                "evaluation_notes",
            ],
        }
        mp.parent.mkdir(parents=True, exist_ok=True)
        with open(mp, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)
        print(f"Saved dataset manifest to {mp}")

    print("\nDataset validation successful! Exactly 100 unique questions, 20 per category.")
    print(f"SHA-256 Checksum: {checksum}")


if __name__ == "__main__":
    validate_and_generate_dataset()
